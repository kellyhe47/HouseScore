/**
 * Derive the map ramp's stops from the published recalculation report (R38).
 *
 * The V1 ramp's hand-picked stops (25/45/65/85) rendered the V2 distribution —
 * ~538 of 540 doors in 0–80, q50 of 11 — as one pale wash. The recalibrated
 * ramp takes its interior stops from `eval/report.json`
 * `score_distribution.quantiles`, so a re-run that shifts the distribution
 * regenerates the stops rather than leaving a stale hand-picked set behind.
 *
 * Run via `npm test` (pretest) or directly:
 *   node web/scripts/gen-ramp-stops.mjs
 *
 * Writes web/js/ramp-stops.js — a generated module, never edited by hand.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const reportUrl = new URL('../../eval/report.json', import.meta.url);
const report = JSON.parse(readFileSync(reportUrl, 'utf8'));

const QUANTILE_KEYS = ['q10', 'q20', 'q30', 'q40', 'q50', 'q60', 'q70', 'q80', 'q90'];
const quantiles = QUANTILE_KEYS.map((key) => {
  const value = report.score_distribution.quantiles[key];
  if (!Number.isFinite(value)) throw new Error(`eval/report.json is missing quantile ${key}`);
  return Math.round(value);
});

// Distinct quantile values ascending, framed by the 0 and 100 endpoints (R1).
const interior = [...new Set(quantiles)].sort((a, b) => a - b).filter((q) => q > 0 && q < 100);
const stopScores = [0, ...interior, 100];

/**
 * The colour curve is the approved prototype's light→dark blue palette
 * (docs/prototype-decoded.html:922). Each channel decreases monotonically
 * along the curve, so sampling it at evenly spaced positions — one per stop —
 * keeps `scoreColor` monotone while spending the palette's full contrast on
 * the quantiles, where the doors actually are.
 */
const CURVE = [
  [237, 239, 242],
  [191, 208, 226],
  [127, 163, 201],
  [65, 114, 159],
  [30, 76, 126],
  [18, 47, 85],
];

function sampleCurve(t) {
  const scaled = t * (CURVE.length - 1);
  const low = Math.min(CURVE.length - 2, Math.floor(scaled));
  const frac = scaled - low;
  return CURVE[low].map((v, ch) => Math.round(v + (CURVE[low + 1][ch] - v) * frac));
}

const stops = stopScores.map((score, index) => {
  const t = index / (stopScores.length - 1);
  return [score, ...sampleCurve(t)];
});

const body = `/**
 * GENERATED by web/scripts/gen-ramp-stops.mjs — do not edit.
 *
 * Interior stops are the documented quantiles of the R34 recalculation report
 * (eval/report.json score_distribution.quantiles), deduped and framed by the
 * 0 and 100 endpoints (R38). Colours are the approved prototype's blue curve
 * sampled evenly across the stops, so contrast is spent where the observed
 * distribution actually lives.
 */

/** @type {ReadonlyArray<readonly [number, number, number, number]>} [score, r, g, b] */
export const STOPS = ${JSON.stringify(stops)};
`;

writeFileSync(new URL('../js/ramp-stops.js', import.meta.url), body);
console.log(`ramp stops derived from report quantiles: [${stopScores.join(', ')}]`);
